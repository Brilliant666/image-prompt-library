def function(name, arguments, call_id):
    return {'type': 'function_call', 'id': call_id, 'call_id': call_id,
            'name': name, 'arguments': json.dumps(arguments, ensure_ascii=False)}


def task_arguments(task, operations):
    return {'taskId': task['taskId'], 'taskRevision': task['revision'],
            'branchRoundId': task['branchRoundId'], 'operations': operations}


def stored_rows(library, identities):
    """Compare preserved JSON bytes, rather than only its public projection."""
    with connect(library) as conn:
        return {identity: {
            'round': conn.execute('SELECT data FROM agent_rounds WHERE request_id=?', (identity,)).fetchone()[0],
            'frozen': tuple(conn.execute('SELECT body,frozen,history FROM agent_requests WHERE id=?',
                                         (identity,)).fetchone()),
        } for identity in identities}


def frozen_request(library, identity):
    with connect(library) as conn:
        return tuple(conn.execute('SELECT body,frozen,history FROM agent_requests WHERE id=?',
                                  (identity,)).fetchone())


def image_transport(provider, monkeypatch):
    """Capture the actual Images multipart payload, including image file bytes."""
    original, images = provider.handle, []

    def capture(request):
        if '/images/' in request.url.path:
            raw = request.read()
            content_type = request.headers.get('content-type', '')
            files = []
            if content_type.startswith('multipart/form-data'):
                mime = BytesParser(policy=policy.default).parsebytes(
                    b'Content-Type: ' + content_type.encode('ascii') + b'\r\nMIME-Version: 1.0\r\n\r\n' + raw)
                files = [part.get_payload(decode=True) for part in mime.iter_parts()
                         if part.get_filename() is not None]
            images.append({'path': request.url.path, 'raw': raw, 'files': files})
        response = original(request)
        if '/images/' in request.url.path and response.status_code == 200:
            # Preview's regular geometric outputs cycle every three calls.
            # Distinct generated bytes are essential to prove that no old
            # picture was silently reused as the new cat's visual evidence.
            output = BytesIO()
            Image.new('RGB', (37, 29), (9, 117, 230)).save(output, format='PNG')
            return httpx.Response(200, json={'data': [{'b64_json': base64.b64encode(output.getvalue()).decode()}]})
        return response

    monkeypatch.setattr(provider, 'handle', capture)
    return images


def old_chat(client, provider, seeds, library, plans, *, retain_target=True):
    """A real long-lived chat task: three old pictures and exact text sources.

    The normal model state tool keeps these turns in one chat task. This is a
    deterministic pre-existing task, not a heuristic classification of prose.
    """
    repo = AgentRepository(library)
    identities, prompts, parent = [], {}, None
    source_ids = [entry['uploadId'] for entry in seeds['images'][:3]]
    assert len(source_ids) == 3

    for index in range(5):
        identity = f'old-chat-{index + 1}'
        prompt = f'EXACT_OLD_SOURCE_{index + 1}: ' + (f'Keep historical detail {index + 1}; punctuation.\n' * 35) + '  '

        def answer(body, index=index):
            task = provider.task_context(body)
            ops = [{'op': 'set_target', 'ref': 'round-1-reference-1' if retain_target and index == 4 else None},
                   {'op': 'set_auxiliaries', 'auxiliaries': []},
                   {'op': 'set_task_type', 'taskType': 'chat'},
                   {'op': 'set_unresolved', 'items': []}]
            return [message(f'Archived synthetic observation {index + 1}'),
                    function('update_task_context', task_arguments(task, ops), f'old-state-{index + 1}')]

        parent = turn(client, plans, identity, prompt, parent=parent,
                      refs=[{'kind': 'upload', 'uploadId': source_ids[index]}] if index < 3 else [],
                      output=answer)
        identities.append(identity)
        prompts[parent] = prompt
    current = repo.request(identities[-1])['round']['taskContext']
    assert current['taskType'] == 'chat'
    assert len({repo.request(identity)['round']['taskContext']['taskId'] for identity in identities}) == 1
    assert len([item for item in current['historyDependencies']
                if item['reason'] == 'unreconciled_user_addition']) >= 3
    if retain_target:
        assert current['target']['assetId'] == source_ids[0]
    else:
        assert current['target'] is None
    return parent, identities, prompts, source_ids


def inline_generation(provider, prompt, *, observed=None, repo=None, identity=None,
                      bad_quote=False, bad_selection=False, bad_prompt_ref=False):
    def answer(body):
        task = provider.task_context(body)
        if observed is not None:
            observed.update(task=copy.deepcopy(repo.request(identity)['round']['taskContext']),
                            editing=copy.deepcopy(repo.request(identity)['round'].get('editingTask')),
                            frozen=frozen_request(repo.library, identity))
        arguments = {
            'images': [{'id': 'one', 'prompt': 'A synthetic cat, no historical objects.' +
                        (' <ref id="round-999-image-1" />' if bad_prompt_ref else '')}],
            'taskContextUpdate': task_arguments(task, [{'op': 'start_task', 'taskType': 'image_generation',
                                                       'sourceQuote': prompt + ' invented' if bad_quote else prompt}]),
            'referenceSelection': {'targetRef': 'round-999-image-1' if bad_selection else None,
                                   'auxiliaries': []},
            'finish_after_generation': True,
        }
        return [function('generate_image_batch', arguments, 'cat-inline-call')]
    return answer


def test_normal_new_cat_task_and_followup_use_only_their_own_actual_image_bytes(preview, monkeypatch):
    client, provider, seeds, library = preview
    plans, wires = scripted(provider, monkeypatch)
    image_wires = image_transport(provider, monkeypatch)
    repo = AgentRepository(library)
    parent, old_ids, _, old_images = old_chat(client, provider, seeds, library, plans)
    archived = stored_rows(library, old_ids)
    old_task_id = repo.request(old_ids[-1])['round']['taskContext']['taskId']
    before = provider.counts.copy()
    observed, prompt = {}, '生成一张猫咪的图'
    cat = turn(client, plans, 'cat', prompt, parent=parent, images=True,
               output=inline_generation(provider, prompt, observed=observed, repo=repo, identity='cat'))
    cat_request = repo.request('cat')
    state = cat_request['round']['taskContext']
    assert state['taskId'] != old_task_id and state['taskType'] == 'image_generation'
    assert state['startRoundId'] == cat and state['sourceRoundIds'] == [cat]
    assert state['target'] is None and state['auxiliaries'] == []
    assert state['historyDependencies'] == [] and state['unresolvedItems'] == []
    assert provider.counts['responses'] - before['responses'] == 1
    assert provider.counts['images'] - before['images'] == 1
    assert image_wires[-1]['path'].endswith('/images/generations') and image_wires[-1]['files'] == []
    cat_job = repo.jobs.get_job(cat_request['round']['outputTaskIds'][0])
    assert cat_job.status == 'succeeded' and cat_job.mode == 'text_to_image'
    assert not cat_job.parameters.get('input_images')
    assert frozen_request(library, 'cat') == observed['frozen']
    assert stored_rows(library, old_ids) == archived

    cat_asset = repo.resolve_ref({'kind': 'job', 'jobId': cat_job.id})
    expected_pixels = repo.data_url(cat_asset)
    before = provider.counts.copy()

    def petting(body):
        task = provider.task_context(body)
        assert task['taskId'] == state['taskId']
        assert set(pixels({'body': body})) == {expected_pixels}
        ref = task['target']['ref']
        return [function('generate_image_batch', {
            'images': [{'id': 'petting', 'prompt': f'A hand gently petting the same cat. <ref id="{ref}" />'}],
            'referenceSelection': {'targetRef': ref, 'auxiliaries': []},
            'finish_after_generation': True}, 'petting-call')]

    cat_frozen = stored_rows(library, ['cat'])
    turn(client, plans, 'petting-cat', '生成一张撸猫的图', parent=cat,
         refs=[{'kind': 'job', 'jobId': cat_job.id}], images=True, output=petting)
    followup = repo.request('petting-cat')
    assert followup['round']['taskContext']['taskId'] == state['taskId']
    assert followup['round']['taskContext']['target']['assetId'] == cat_asset
    followup_job = repo.jobs.get_job(followup['round']['outputTaskIds'][0])
    assert followup_job.status == 'succeeded' and followup_job.mode == 'image_edit'
    assert len(followup_job.parameters['input_images']) == 1
    assert provider.counts['responses'] - before['responses'] == 1
    assert provider.counts['images'] - before['images'] == 1
    assert image_wires[-1]['path'].endswith('/images/edits')
    assert image_wires[-1]['files'] == [base64.b64decode(expected_pixels.split(',', 1)[1])]
    assert set(pixels(next(wire for wire in reversed(wires) if 'body' in wire))) == {expected_pixels}
    assert not set(repo.data_url(aid) for aid in old_images) & set(pixels(next(wire for wire in reversed(wires) if 'body' in wire)))
    assert stored_rows(library, old_ids) == archived and stored_rows(library, ['cat']) == cat_frozen
    assert not plans and provider.counts['blocked'] == 0


