def test_inline_task_update_recovers_after_job_creation_without_a_second_cas_or_job(preview, monkeypatch):
    from backend.services import agent_execution
    client, provider, seeds, library = preview
    plans, _ = scripted(provider, monkeypatch)
    image_wires = image_transport(provider, monkeypatch)
    repo = AgentRepository(library)
    parent, old_ids, _, _ = old_chat(client, provider, seeds, library, plans)
    archived, before, observed = stored_rows(library, old_ids), provider.counts.copy(), {}
    create_job, run_request = agent_execution.create_image_job, agent_execution.run_request
    created, exited = [], Event()

    class SyntheticWorkerExit(BaseException):
        """Bypass normal Exception recovery, as a worker/process exit would."""

    def worker(*args, **kwargs):
        try:
            return run_request(*args, **kwargs)
        finally:
            exited.set()

    def interrupt_after_create(*args, **kwargs):
        job = create_job(*args, **kwargs)
        created.append(job.id)
        raise SyntheticWorkerExit()

    monkeypatch.setattr(agent_execution, 'create_image_job', interrupt_after_create)
    monkeypatch.setattr(agent_execution, 'run_request', worker)
    prompt = '生成一张猫咪的图'
    plans.append(inline_generation(provider, prompt, observed=observed, repo=repo, identity='resume-inline'))
    submit(client, 'resume-inline', prompt, parent=parent, images=True)
    assert exited.wait(8), 'the synthetic worker must exit before restart recovery is exercised'
    assert repo.request('resume-inline')['state'] == 'running'
    agent_execution.recover_agent_requests(library)
    interrupted = wait_request(client, 'resume-inline')
    assert interrupted['request']['state'] == 'interrupted' and interrupted['request']['canResume']
    at_crash = copy.deepcopy(repo.request('resume-inline')['round'])
    assert len(created) == 1 and at_crash['outputTaskIds'] == created
    assert not any(item['type'] == 'function_call_output' for item in at_crash['responseOutput'])
    receipts = at_crash.get('_taskUpdateReceipts', {})
    assert len(receipts) == 1, 'the applied task CAS must have a durable same-call receipt before creating a job'
    receipt = next(iter(receipts.values()))
    assert receipt['step'] == 1 and receipt['callId'] == 'cat-inline-call'
    assert receipt['taskId'] == at_crash['taskContext']['taskId']
    assert repo.jobs.get_job(created[0]).status == 'queued' and provider.counts['images'] == before['images']
    monkeypatch.setattr(agent_execution, 'create_image_job', create_job)
    monkeypatch.setattr(agent_execution, 'run_request', run_request)
    resumed = client.post('/api/agent/requests/resume-inline/resume', json={'resumeId': 'resume-inline-once'})
    assert resumed.status_code == 202, resumed.text
    finished = wait_request(client, 'resume-inline')
    assert finished['request']['state'] == 'completed', finished
    saved = repo.request('resume-inline')
    assert saved['round']['outputTaskIds'] == created and saved['usage']['imageJobsCreated'] == 1
    assert saved['round']['taskContext']['taskId'] == at_crash['taskContext']['taskId']
    assert saved['round']['taskContext']['revision'] == at_crash['taskContext']['revision'] + 1, 'only the one executed Prompt receipt advances task revision after resume'
    assert saved['round']['_taskUpdateReceipts'] == receipts
    assert len([item for item in saved['round']['responseOutput'] if item['type'] == 'function_call_output']) == 1
    assert provider.counts['responses'] - before['responses'] == 1
    assert provider.counts['images'] - before['images'] == 1 and len(image_wires) == 1
    assert client.post('/api/agent/requests/resume-inline/resume', json={'resumeId': 'resume-inline-once'}).status_code == 200
    assert provider.counts['responses'] - before['responses'] == 1 and provider.counts['images'] - before['images'] == 1
    assert frozen_request(library, 'resume-inline') == observed['frozen']
    assert stored_rows(library, old_ids) == archived and not plans


def test_candidate_reconciles_each_exact_source_and_later_chat_omits_its_old_transcript(preview, monkeypatch):
    client, provider, seeds, library = preview
    plans, wires = scripted(provider, monkeypatch)
    repo = AgentRepository(library)
    parent, old_ids, old_prompts, _ = old_chat(client, provider, seeds, library, plans, retain_target=False)
    archived, sources = stored_rows(library, old_ids), {}
    prompt = '把已经讨论的要求整理成一份完整候选。'
    candidate_text = 'A complete synthetic scene with the agreed geometric layout and soft light.'

    def candidate(body):
        task = provider.task_context(body)
        required = {item['roundId'] for item in task['historyDependencies']
                    if item['reason'] == 'unreconciled_user_addition'}
        sources.update({rid: old_prompts[rid] for rid in required})
        sources[task['branchRoundId']] = prompt
        operations = [{'op': 'set_prompt', 'kind': 'candidate', 'text': candidate_text}]
        operations += [{'op': 'reconcile_text_source', 'roundId': rid, 'sourceQuote': source}
                       for rid, source in sources.items()]
        return [message(f'```prompt\n{candidate_text}\n```'),
                function('update_task_context', task_arguments(task, operations), 'reconcile-each-source')]

    parent = turn(client, plans, 'candidate', prompt, parent=parent, output=candidate)
    state = repo.request('candidate')['round']['taskContext']
    assert len(sources) >= 4
    assert not state['historyDependencies']
    assert state['selectedPromptVersionId'] is None
    active_candidate = next(version for version in state['promptVersions'] if version['id'] == state['workingPromptVersionId'])
    assert active_candidate['text'] == candidate_text and active_candidate['kind'] == 'candidate'
    assert active_candidate['confirmedBy'] is None
    for rid, source in sources.items():
        receipt = state['_textReconciliations'][rid]
        assert receipt['sourceSha256'] == hashlib.sha256(source.encode('utf-8')).hexdigest()
        assert receipt['promptVersionId'] == active_candidate['id']

    for index in range(2):
        text = f'Continue compact ordinary discussion {index + 1}.'

        def reconciled_answer(body, text=text, index=index):
            task = provider.task_context(body)
            return [message('The agreed candidate remains unconfirmed.'), function('update_task_context', task_arguments(task, [
                {'op': 'reconcile_text_source', 'roundId': task['branchRoundId'], 'sourceQuote': text},
            ]), f'compact-source-{index + 1}')]

        parent = turn(client, plans, f'compact-{index + 1}', text, parent=parent, output=reconciled_answer)
    before = provider.counts.copy()
    turn(client, plans, 'plain-chat', 'What can we discuss next?', parent=parent, output=[message('A compact answer.')])
    final_wire = next(wire for wire in reversed(wires) if 'body' in wire)
    final_json = json.dumps(final_wire['body'], ensure_ascii=False)
    # The original Prompt remains a named immutable version. Reconciled later
    # supplements are no longer repeated as old user/assistant transcript rows.
    for source in list(old_prompts.values())[1:]:
        assert source not in final_json and source[:30] not in final_json
    assert candidate_text in final_json
    assert provider.counts['responses'] - before['responses'] == 1 and provider.counts['images'] == 0
    assert stored_rows(library, old_ids) == archived and not plans


def test_read_task_history_attaches_only_the_requested_ancestor_pixels_on_next_response(preview, monkeypatch):
    client, provider, seeds, library = preview
    plans, wires = scripted(provider, monkeypatch)
    repo = AgentRepository(library)
    parent, old_ids, old_prompts, old_images = old_chat(client, provider, seeds, library, plans, retain_target=False)
    archived, before = stored_rows(library, old_ids), provider.counts.copy()
    expected = repo.data_url(old_images[1])

    def ask_history(body):
        assert pixels({'body': body}) == [], 'old text dependencies must not attach every historical picture'
        return [function('read_task_history', {'roundNumbers': [2]}, 'read-specific-ancestor')]

    def inspect_evidence(body):
        assert set(pixels({'body': body})) == {expected}, 'the next real Responses request must carry the chosen ancestor pixels'
        receipts = [item for item in body['input'] if item.get('type') == 'function_call_output'
                    and item.get('call_id') == 'read-specific-ancestor']
        assert len(receipts) == 1
        evidence = json.loads(receipts[0]['output'])
        assert len(evidence['history']) == 1 and evidence['history'][0]['roundNumber'] == 2
        assert evidence['history'][0]['user'] == list(old_prompts.values())[1]
        return [message('The requested synthetic ancestor pixels were actually inspected.')]

    plans += [ask_history, inspect_evidence]
    submit(client, 'history-pixels', 'Please inspect the earlier visual evidence before answering.', parent=parent)
    finished = wait_request(client, 'history-pixels')
    assert finished['request']['state'] == 'completed', finished
    assert provider.counts['responses'] - before['responses'] == 2 and provider.counts['images'] == 0
    current = repo.request('history-pixels')['round']
    assert current['contextEvidenceRoundIds'] == [repo.request(old_ids[1])['round']['id']]
    assert set(pixels(next(wire for wire in reversed(wires) if 'body' in wire))) == {expected}
    assert stored_rows(library, old_ids) == archived and not plans and provider.counts['blocked'] == 0


def test_native_inline_new_task_uses_one_planning_and_one_native_response_with_one_gallery_job(preview, monkeypatch):
    client, provider, seeds, library = preview
    native_provider = provider.handle
    plans, wires = scripted(provider, monkeypatch)
    planning_provider = provider.handle
    native_wires, native_outputs = [], []

    def transport(request):
        assert '/images/' not in request.url.path, 'Native batch must never fall back to the Images API'
        body = json.loads(request.read())
        if body.get('tool_choice') == {'type': 'image_generation'}:
            native_wires.append(body)
            # This is the original offline provider, not the planning script.
            # It counts this real wire call and returns a completed native
            # image_generation_call with valid synthetic image bytes.
            response = native_provider(request)
            native_outputs.append(response.json())
            return response
        return planning_provider(request)

    monkeypatch.setattr(provider, 'handle', transport)
    repo = AgentRepository(library)
    parent, old_ids, _, _ = old_chat(client, provider, seeds, library, plans)
    old_task = repo.request(old_ids[-1])['round']['taskContext']['taskId']
    set_mode(client, 'native')
    archived, before = stored_rows(library, old_ids), provider.counts.copy()
    planning_before, prompt, observed = len(wires), '生成一张猫咪的图', {}
    cat = turn(client, plans, 'native-cat', prompt, parent=parent, images=True,
               output=inline_generation(provider, prompt, observed=observed, repo=repo, identity='native-cat'))
    saved = repo.request('native-cat')
    state = saved['round']['taskContext']
    assert saved['state'] == 'completed' and saved['upstream_outcome'] == 'known'
    assert saved['usage'] == {'responseStepsStarted': 1, 'imageJobsCreated': 1}
    assert state['taskId'] != old_task and state['taskType'] == 'image_generation'
    assert state['startRoundId'] == cat and state['sourceRoundIds'] == [cat]
    assert state['target'] is None and state['auxiliaries'] == []
    assert state['historyDependencies'] == [] and state['unresolvedItems'] == []
    assert state['executedPromptVersionId'] and state['selectedPromptVersionId'] is None
    assert provider.counts['responses'] - before['responses'] == 2
    assert provider.counts['images'] == 0 and len(wires) - planning_before == 1
    assert len(native_wires) == len(native_outputs) == 1 and not plans
    native = native_wires[0]
    assert native['tool_choice'] == {'type': 'image_generation'} and native['max_tool_calls'] == 1
    assert len(native['tools']) == 1 and native['tools'][0]['type'] == 'image_generation'
    assert pixels({'body': native}) == [], 'the native image request must not inherit the old chat target'
    output = native_outputs[0]['output']
    assert len(output) == 1 and output[0]['type'] == 'image_generation_call' and output[0]['status'] == 'completed'
    result_bytes = base64.b64decode(output[0]['result'])
    with Image.open(BytesIO(result_bytes)) as image:
        image.verify()

    assert len(saved['round']['outputTaskIds']) == 1
    job = repo.jobs.get_job(saved['round']['outputTaskIds'][0])
    assert job.provider == 'agent_native_batch' and job.status == 'succeeded'
    assert job.mode == 'text_to_image' and not job.parameters.get('input_images')
    assert (library / job.result_path).read_bytes() == result_bytes
    gallery = client.get('/api/generation-jobs', params={'prepare_references': False})
    assert gallery.status_code == 200, gallery.text
    assert gallery.json()['total'] == 1
    assert [(row['id'], row['status'], row['provider']) for row in gallery.json()['jobs']] == [
        (job.id, 'succeeded', 'agent_native_batch')]
    media = client.get('/media/' + job.result_path)
    assert media.status_code == 200 and media.content == result_bytes
    calls = [item for item in saved['round']['responseOutput'] if item['type'] == 'function_call']
    receipts = [item for item in saved['round']['responseOutput'] if item['type'] == 'function_call_output']
    assert [call['name'] for call in calls] == ['generate_image_batch']
    assert len(receipts) == 1 and receipts[0]['call_id'] == calls[0]['call_id']
    assert json.loads(receipts[0]['output'])['images'] == [{'id': 'one', 'status': 'done'}]
    assert frozen_request(library, 'native-cat') == observed['frozen']
    assert stored_rows(library, old_ids) == archived and provider.counts['blocked'] == 0
